export function buildMinecraftBodyRenderUrl(minecraftUuid: string): string {
  return `https://mc-heads.net/body/${minecraftUuid}`
}

export function buildMinecraftHeadRenderUrl(minecraftUuid: string): string {
  return `https://mc-heads.net/head/${minecraftUuid}`
}

export function buildMinecraftAvatarIconUrl(minecraftUuid: string): string {
  return `https://mc-heads.net/avatar/${minecraftUuid}`
}
